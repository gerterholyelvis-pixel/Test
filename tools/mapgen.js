// tools/mapgen.js: regenerates the generated half of docs/MAP.md (file index + tagged-block index) so agents can Grep a tag
// instead of reading game.js / server.js. Pure read of the source tree, no dependencies.
//   node tools/mapgen.js            rewrite the block between <!-- MAPGEN-BEGIN --> and <!-- MAPGEN-END --> in docs/MAP.md
//   node tools/mapgen.js --print    print the index to stdout (fresh line numbers, nothing written)
//   node tools/mapgen.js --print PANEL   only blocks / files whose name contains PANEL (case-insensitive)
//   node tools/mapgen.js --check    exit 1 if a BEGIN has no END (or the other way round); prints the offenders
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..');
const MAP = path.join(ROOT, 'docs', 'MAP.md');

function srcFiles() {
  const out = fs.readdirSync(ROOT).filter(f => f.endsWith('.js')).sort();
  const walk = d => { for (const f of fs.readdirSync(path.join(ROOT, d)).sort()) { const r = d + '/' + f, st = fs.statSync(path.join(ROOT, r)); if (st.isDirectory()) walk(r); else if (f.endsWith('.js')) out.push(r); } };
  if (fs.existsSync(path.join(ROOT, 'client'))) walk('client');
  return out;
}
const clip = (s, n) => { s = s.replace(/\s+/g, ' ').trim(); return s.length > n ? s.slice(0, n - 1).trimEnd() + '…' : s; };
const cell = s => s.replace(/\|/g, '\\|');

// Tagged blocks: `NAME-BEGIN ... NAME-END` (NAME may have dashes: STATIONS-CRAFT, RULES-LOGIC). Blocks whose BEGIN and END sit on the
// same line are inline markers; they are counted per tag but not listed.
function blocks(file, text) {
  const lines = text.split(/\r?\n/), open = {}, res = [], inline = {}, bad = [];
  const re = /\b([A-Z][A-Z0-9_]*(?:-[A-Z0-9_]+)*?)-(BEGIN|END)\b/g;
  lines.forEach((ln, i) => {
    const seen = [];
    for (let m; (m = re.exec(ln));) if (!/\b(the|see|in|a|its)\s+$/i.test(ln.slice(0, m.index))) seen.push([m[1], m[2], m.index + m[0].length]);   // "see the ACT5-BEGIN block" is prose, not a tag
    const begun = new Set(seen.filter(s => s[1] === 'BEGIN').map(s => s[0]));
    for (const [name, kind, end] of seen) {
      if (kind === 'BEGIN') {
        if (seen.some(s => s[0] === name && s[1] === 'END')) { inline[name] = (inline[name] || 0) + 1; continue; }
        let desc = ln.slice(end).replace(/^[\s:)(.*/-]+/, '').replace(/\*\/.*$/, '').trim();
        if (/\)$/.test(desc) && !desc.includes('(')) desc = desc.slice(0, -1);   // "(door textures: owned by X)" -> no stray ")"
        if (!desc) desc = ln.slice(0, end - name.length - 6).replace(/^\s*(\/\/|\/\*)\s*/, '').replace(/[-\s(]+$/, '').trim();
        (open[name] = open[name] || []).push({ name, file, start: i + 1, desc });
      } else {
        if (begun.has(name)) continue;
        const st = open[name] && open[name].pop();
        if (!st) { bad.push(file + ':' + (i + 1) + ' ' + name + '-END without BEGIN'); continue; }
        st.end = i + 1; res.push(st);
      }
    }
  });
  for (const k in open) for (const st of open[k]) bad.push(file + ':' + st.start + ' ' + k + '-BEGIN without END');
  res.sort((a, b) => a.start - b.start);
  return { res, inline, bad };
}

// Per-file facts: lines, KB, header comment, browser globals and CommonJS exports it defines.
function facts(file, text) {
  const lines = text.split(/\r?\n/);
  const head = (lines.find(l => /^\s*(\/\/|\/\*)/.test(l)) || '').replace(/^\s*(\/\/|\/\*+)\s*/, '').replace(/\*\/.*$/, '');
  const g = new Set(); for (const m of text.matchAll(/\b(?:window|root|globalThis|self)\.(GK[A-Z0-9_]*|VB5)\s*=(?!=)/g)) g.add(m[1]);
  let exp = ''; const em = text.match(/module\.exports\s*=\s*(\{[^\n]*)/);
  if (em) exp = clip(em[1].replace(/\{|\}.*$/g, '').split(',').map(s => s.split(':')[0].trim()).filter(s => /^[A-Za-z_$][\w$]*$/.test(s)).join(', '), 140);
  const crlf = /\r\n/.test(text);
  return { file, lines: lines.length, kb: Math.round(text.length / 1024), head: clip(head, 150), globals: [...g].join(', '), exp, crlf };
}

function build(filter) {
  const F = filter && filter.toLowerCase(), rows = [], blk = [], bad = [], inl = [];
  for (const f of srcFiles()) {
    const text = fs.readFileSync(path.join(ROOT, f), 'utf8'), fa = facts(f, text), b = blocks(f, text);
    bad.push(...b.bad);
    if (!F || f.toLowerCase().includes(F)) rows.push(fa);
    for (const x of b.res) if (!F || x.name.toLowerCase().includes(F) || f.toLowerCase().includes(F)) blk.push(x);
    const ik = Object.keys(b.inline).sort(); if (ik.length && (!F || f.toLowerCase().includes(F))) inl.push(f + ': ' + ik.map(k => k + ' x' + b.inline[k]).join(', '));
  }
  const L = [];
  L.push('Generated by `node tools/mapgen.js`. Line numbers drift with every edit: **Grep the tag** (`Grep "PANEL-BEGIN" game.js`), then Read with offset/limit. Do not hand-edit this part; on a merge conflict take either side and rerun the tool.', '');
  L.push('### Files', '', '| file | lines | KB | EOL | defines | header |', '|---|---:|---:|---|---|---|');
  for (const r of rows) L.push('| `' + r.file + '` | ' + r.lines + ' | ' + r.kb + ' | ' + (r.crlf ? 'CRLF' : 'LF') + ' | ' + cell([r.globals, r.exp && 'exports: ' + r.exp].filter(Boolean).join('; ')) + ' | ' + cell(r.head) + ' |');
  L.push('', '### Tagged blocks', '', '| tag | file | lines | what |', '|---|---|---|---|');
  for (const x of blk) L.push('| `' + x.name + '` | ' + x.file + ' | ' + x.start + '-' + x.end + ' (' + (x.end - x.start + 1) + ') | ' + cell(clip(x.desc, 130)) + ' |');
  if (inl.length) L.push('', 'Inline one-line markers (not listed above): ' + inl.join('; ') + '.');
  if (bad.length) L.push('', '**Unbalanced tags:** ' + bad.join('; '));
  return { text: L.join('\n'), bad };
}

const args = process.argv.slice(2);
if (args[0] === '--check') { const { bad } = build(); if (bad.length) { console.log('unbalanced block tags:\n  ' + bad.join('\n  ')); process.exit(1); } console.log('block tags balanced'); }
else if (args[0] === '--print') console.log(build(args[1]).text);
else {
  const gen = build().text, cur = fs.existsSync(MAP) ? fs.readFileSync(MAP, 'utf8') : '# Repo map\n\n<!-- MAPGEN-BEGIN -->\n<!-- MAPGEN-END -->\n';
  const a = cur.indexOf('<!-- MAPGEN-BEGIN -->'), b = cur.indexOf('<!-- MAPGEN-END -->');
  if (a < 0 || b < a) { console.error('docs/MAP.md has no <!-- MAPGEN-BEGIN --> / <!-- MAPGEN-END --> markers'); process.exit(1); }
  fs.writeFileSync(MAP, cur.slice(0, a) + '<!-- MAPGEN-BEGIN -->\n' + gen + '\n' + cur.slice(b));
  console.log('docs/MAP.md updated (' + gen.split('\n').length + ' generated lines)');
}
